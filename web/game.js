// ---------------------------------------------------------------- bikes
function presetParams(name) {
  if (name === 'custom') { const c = store.get('customBike', null); if (c) return Int32Array.from(c); name = 'expert'; }
  name === 'beginner' ? M._web_bike_beginner() : M._web_bike_expert();
  const p = M._web_bike_params() >> 2;
  return Int32Array.from(M.HEAP32.subarray(p, p + 27));
}
function customHash() { const c = store.get('customBike', []); let h = 0; for (const v of c) h = (h * 31 + v) | 0; return (h >>> 0).toString(36); }

