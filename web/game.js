// ---------------------------------------------------------------- settings / storage
const store = {
  get(k, d) { try { const v = localStorage.getItem('db.' + k); return v === null ? d : JSON.parse(v); } catch (e) { return d; } },
  set(k, v) { try { localStorage.setItem('db.' + k, JSON.stringify(v)); } catch (e) { /* quota */ } },
};
function settings() {
  return {track: $('track').value, seed: $('seed').value | 0, bike: $('bike').value, physics: $('physics').value,
    manual: $('trans').value === 'manual', ghosts: $('ghosts').checked, sound: $('sound').checked};
}
function trackId(s) { return s.track === 'random' ? 'seed:' + (s.seed >>> 0) : s.track; }
function bestKey(s) { return `best|${trackId(s)}|${s.physics}|${s.bike}${s.bike === 'custom' ? ':' + customHash() : ''}`; }

// ---------------------------------------------------------------- bikes
function presetParams(name) {
  if (name === 'custom') { const c = store.get('customBike', null); if (c) return Int32Array.from(c); name = 'expert'; }
  name === 'beginner' ? M._web_bike_beginner() : M._web_bike_expert();
  const p = M._web_bike_params() >> 2;
  return Int32Array.from(M.HEAP32.subarray(p, p + 27));
}
function customHash() { const c = store.get('customBike', []); let h = 0; for (const v of c) h = (h * 31 + v) | 0; return (h >>> 0).toString(36); }

// ---------------------------------------------------------------- tracks
function loadTrack(s) {
  const id = trackId(s);
  let t;
  if (id === 'beginner' || id === 'expert' || id.startsWith('seed:')) {
    const seed = id === 'beginner' ? BEGINNER_SEED : id === 'expert' ? EXPERT_SEED : +id.slice(5);
    M._web_track_generate(seed >>> 0);
    const n = M._web_track_n(), p = M._web_track_points() >> 2, pts = [];
    for (let i = 0; i < n; i++) pts.push([M.HEAP32[p + 2 * i], M.HEAP32[p + 2 * i + 1]]);
    const name = id === 'beginner' ? "Beginner's Track" : id === 'expert' ? "Expert's Track" : `Random track ${seed >>> 0}`;
    t = {id, name, laps: M._web_track_laps(), allowGetBack: M._web_track_allow_get_back(), pts, ghosts: [],
      description: `This track was generated by the random track generator, using a seed number of ${seed | 0}`};
  } else {
    const src = window.DB_TRACKS.find(x => x.name === id);
    const p = M._web_track_points() >> 2;
    src.points.forEach((q, i) => { M.HEAP32[p + 2 * i] = q[0]; M.HEAP32[p + 2 * i + 1] = q[1]; });
    M._web_track_set(src.points.length, src.laps, src.allow_get_back);
    t = {id, name: src.name, description: src.description, laps: src.laps, allowGetBack: src.allow_get_back,
      pts: src.points, ghosts: src.ghosts.map(g => ({...g, color: 'rgba(40,70,255,0.45)'}))};
  }
  const path = new Path2D();
  path.moveTo(t.pts[0][0], -1e6);
  for (const q of t.pts) path.lineTo(q[0], q[1]);
  path.lineTo(t.pts[t.pts.length - 1][0], -1e6);
  path.closePath();
  const edge = new Path2D();
  t.pts.forEach((q, i) => i ? edge.lineTo(q[0], q[1]) : edge.moveTo(q[0], q[1]));
  t.path = path; t.edge = edge;
  t.lapLength = t.pts[t.pts.length - 100][0] - t.pts[0][0];
  // parallax hills
  let seed = 12345; const rnd = () => (seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
  t.hills = [0, 1].map(layer => { const h = []; for (let i = 0; i < 64; i++) h.push(rnd()); return h; });
  return t;
}

// ---------------------------------------------------------------- sound
const audio = {ctx: null, buf: {}, engine: null, engineGain: null, lastBottom: 0};
async function initAudio() {
  if (audio.ctx || !window.DB_SOUNDS) return;
  audio.ctx = new (window.AudioContext || window.webkitAudioContext)();
  for (const [k, url] of Object.entries(window.DB_SOUNDS)) {
    try { audio.buf[k] = await audio.ctx.decodeAudioData(await (await fetch(url)).arrayBuffer()); } catch (e) { console.warn('sound', k, e); }
  }
}
function play(name, vol = 0.6) {
  if (!settings().sound || !audio.ctx || !audio.buf[name]) return null;
  const src = audio.ctx.createBufferSource(), g = audio.ctx.createGain();
  src.buffer = audio.buf[name]; g.gain.value = vol;
  src.connect(g).connect(audio.ctx.destination); src.start();
  return src;
}
function startEngineSound() {
  stopEngineSound();
  if (!settings().sound || !audio.ctx || !audio.buf.engine) return;
  const src = audio.ctx.createBufferSource(), g = audio.ctx.createGain();
  src.buffer = audio.buf.engine; src.loop = true; g.gain.value = 0;
  src.connect(g).connect(audio.ctx.destination); src.start();
  audio.engine = src; audio.engineGain = g;
}
function stopEngineSound() { if (audio.engine) { audio.engine.stop(); audio.engine = null; } }

// ---------------------------------------------------------------- race lifecycle
function startRace() {
  const s = settings();
  track = loadTrack(s);
  bikeParams = presetParams(s.bike);
  bikeParams[26] = s.manual ? 0 : 1;
  const p = M._web_bike_params() >> 2;
  M.HEAP32.set(bikeParams, p);
  M._web_new_race(s.physics === 'improved' ? 1 : 0, 0);
  const best = store.get(bestKey(s), null);
  const ghosts = s.ghosts ? [...track.ghosts] : [];
  if (s.ghosts && best && best.samples) ghosts.push({name: 'Your best', radii: [bikeParams[0], bikeParams[8]], samples: best.samples, color: 'rgba(40,200,60,0.5)'});
  race = {s, ghosts, best: best ? best.time : null, prev: readState(), unitsAcc: 0, samples: [], msg: '', msgUntil: 0,
    done: false, camY: null, lastSample: -1};
  throttle = 0;
  $('menu').classList.add('hidden');
  $('hud').classList.remove('hidden'); $('status').classList.remove('hidden');
  if (audio.ctx && audio.ctx.state === 'suspended') audio.ctx.resume();
  startEngineSound();
  flash(s.manual ? 'Press → or click to start your engine' : 'Get ready', 2500, true);
  updateStatus();
}
function readState() { const p = M._web_state() >> 3; return Array.from(M.HEAPF64.subarray(p, p + 26)); }
function flash(text, ms, small) { race.msg = small ? `<small>${text}</small>` : text; race.msgUntil = performance.now() + ms; }
function showMenu() {
  stopEngineSound();
  race = null;
  $('menu').classList.remove('hidden');
  $('hud').classList.add('hidden'); $('status').classList.add('hidden'); $('msg').innerHTML = '';
  updateMenu();
}
function finishRace(st) {
  race.done = true;
  const t = st[S.FINISH_TIME];
  if (!st[S.FINISHED_OK]) { flash('Crashed out!\n<small>R: try again · Esc: menu</small>', 1e9); return; }
  let line = `Finished: ${(t / 1000).toFixed(3)} s`;
  if (race.best === null || t < race.best) {
    store.set(bestKey(race.s), {time: t, samples: race.samples});
    line += race.best === null ? '\n<small>first time on record</small>' : `\n<small>New best! (was ${(race.best / 1000).toFixed(3)} s)</small>`;
    play('hooray');
  } else line += `\n<small>best ${(race.best / 1000).toFixed(3)} s</small>`;
  race.msg = line + '\n<small>R: ride again · Esc: menu</small>'; race.msgUntil = 1e15;
}

// ---------------------------------------------------------------- input
function setThrottleFromY(clientY) {
  const f = clientY / cv.clientHeight;
  throttle = Math.max(0, Math.min(TMAX, Math.round((BRAKE_FRAC - f) * 480) * 200));
  kbMode = false;
}
cv.addEventListener('mousemove', e => setThrottleFromY(e.clientY));
cv.addEventListener('touchstart', e => { setThrottleFromY(e.touches[0].clientY); e.preventDefault(); }, {passive: false});
cv.addEventListener('touchmove', e => { setThrottleFromY(e.touches[0].clientY); e.preventDefault(); }, {passive: false});
cv.addEventListener('mousedown', e => { if (race && !race.done && e.button === 0) M._web_shift(1); });
document.addEventListener('keydown', e => {
  keys[e.key] = true;
  if (!$('editor').style.display || $('editor').style.display === 'none') {
    if (race) {
      if (e.key === 'ArrowRight' || e.key === 'd') M._web_shift(1);
      else if (e.key === 'ArrowLeft' || e.key === 'a') M._web_shift(-1);
      else if (e.key === 'r' || e.key === 'R') startRace();
      else if (e.key === 'Escape') showMenu();
      else if (e.key === 'p' || e.key === 'P') paused = !paused;
      if (['ArrowUp', 'ArrowDown', 'ArrowLeft', 'ArrowRight', ' '].includes(e.key)) e.preventDefault();
    } else if (e.key === 'Enter') { begin(); }
  }
});
document.addEventListener('keyup', e => { keys[e.key] = false; });

// ---------------------------------------------------------------- per-frame update
function update(ms) {
  if (!race || paused) return;
  if (keys.ArrowUp || keys.w || keys.ArrowDown || keys.s) {
    kbMode = true;
    throttle += ((keys.ArrowUp || keys.w) ? 1 : -1) * 150 * ms; // original keys: +-15 per 0.1 ms
    throttle = Math.max(0, Math.min(TMAX, throttle));
  }
  M._web_set_throttle(Math.round(throttle));
  if (race.done) return;
  race.unitsAcc += Math.min(ms, 100) * 10;
  const units = Math.floor(race.unitsAcc);
  race.unitsAcc -= units;
  if (units < 1) return;
  M._web_advance(units);
  const st = readState(), pv = race.prev;
  events(st, pv);
  race.prev = st;
  if (st[S.STATE] === 2 && st[S.RACE_TIME] - race.lastSample >= 50) {
    const th = Math.round((st[S.ANGLE]) / 0.0572958);
    race.samples.push([Math.round(st[S.X]), Math.round(st[S.Y]), Math.round(st[S.FWX] - st[S.X]), Math.round(st[S.FWY] - st[S.Y]),
      Math.round(st[S.RWX] - st[S.X]), Math.round(st[S.RWY] - st[S.Y]), th, st[S.RACE_TIME]]);
    race.lastSample = st[S.RACE_TIME];
  }
  if (st[S.FINISH_TIME]) finishRace(st);
}
function events(st, pv) {
  if (pv[S.STATE] === 0 && st[S.STATE] === 1) flash('Ready…', 1200);
  if (pv[S.STATE] === 1 && st[S.STATE] === 2) { flash('GO!', 700); play('go'); }
  if (st[S.CRASHES] > pv[S.CRASHES]) {
    play('crash');
    if (!st[S.FINISH_TIME]) flash(race.s.manual ? 'CRASH!\n<small>→ / click to restart the engine</small>' : 'CRASH!', 1500);
  }
  if (st[S.LAPS] > pv[S.LAPS] && !st[S.FINISH_TIME]) { flash(`Lap ${st[S.LAPS] + 1} / ${track.laps}`, 1200); play('lap'); }
  if (Math.abs(st[S.ANGLE] - pv[S.ANGLE]) > 180 && st[S.CRASHES] === pv[S.CRASHES]) play('whoa'); // full rotation
  const now = performance.now();
  if (((st[S.FRONT_EXT] <= 0 && pv[S.FRONT_EXT] > 0) || (st[S.REAR_EXT] <= 0 && pv[S.REAR_EXT] > 0)) && now - audio.lastBottom > 250) {
    play('bottom', 0.5); audio.lastBottom = now;
  }
  if (audio.engine) {
    audio.engine.playbackRate.setTargetAtTime((Math.max(0, st[S.RPM]) + 40000) / 65536, audio.ctx.currentTime, 0.02);
    audio.engineGain.gain.setTargetAtTime(st[S.ENGINE] ? 0.22 : 0, audio.ctx.currentTime, 0.05);
  }
}

// ---------------------------------------------------------------- rendering
function wheel(x, y, r, ang, col) {
  cx.lineWidth = 45; cx.strokeStyle = col;
  cx.beginPath(); cx.arc(x, y, r - 20, 0, 7); cx.stroke();
  if (ang === null) return;
  cx.lineWidth = 12; cx.beginPath();
  for (let k = 0; k < 6; k++) { const a = ang + k * Math.PI / 3; cx.moveTo(x, y); cx.lineTo(x + Math.cos(a) * (r - 40), y + Math.sin(a) * (r - 40)); }
  cx.stroke();
  cx.fillStyle = col; cx.beginPath(); cx.arc(x, y, 45, 0, 7); cx.fill();
}
// Bike + rider in the bike's frame: a along the rear->front wheel axis, b perpendicular (up), origin at the
// centre of gravity. Proportions follow the original's level sprite (PICT 143): bodywork just above the wheel
// tops, rider crouched on the pegs with hips ~300 mm and head ~1000 mm above the CG.
const PLAYER_STYLE = {body: '#3cb043', engine: '#2b2b2b', metal: '#b8b8b8', tire: '#1a1a1a', suit: '#203a8a', helmet: '#f2f2f2', cg: '#e01010'};
function ghostStyle(c) { return {body: c, engine: c, metal: c, tire: c, suit: c, helmet: c, cg: null}; }
function drawBike(x, y, fwx, fwy, rwx, rwy, fr, rr, st, af, ar) {
  const fx = fwx - rwx, fy = fwy - rwy, fl = Math.hypot(fx, fy) || 1, ux = fx / fl, uy = fy / fl, nx = -uy, ny = ux;
  const P = (a, b) => [x + ux * a + nx * b, y + uy * a + ny * b];
  const poly = (pts, fill) => { cx.fillStyle = fill; cx.beginPath(); pts.forEach((q, i) => cx[i ? 'lineTo' : 'moveTo'](...P(...q))); cx.closePath(); cx.fill(); };
  const line = (pts, w, col) => { cx.lineWidth = w; cx.strokeStyle = col; cx.beginPath(); pts.forEach((q, i) => cx[i ? 'lineTo' : 'moveTo'](...q)); cx.stroke(); };
  cx.lineCap = 'round'; cx.lineJoin = 'round';
  wheel(fwx, fwy, fr, af, st.tire); wheel(rwx, rwy, rr, ar, st.tire);
  line([P(-80, -180), [rwx, rwy]], 70, st.metal);                       // swingarm
  line([[fwx, fwy], P(330, 330)], 60, st.metal);                        // fork
  line([P(330, 330), P(290, 470), P(380, 480)], 40, st.metal);          // bars
  poly([[-200, -260], [220, -260], [260, 60], [-160, 80]], st.engine);  // engine
  poly([[-480, 40], [-100, 40], [-60, 250], [-520, 230]], st.body);     // side panel
  line([P(-880, 190), P(-560, 240), P(-80, 260), P(100, 290)], 90, st.body); // seat / rear fender
  poly([[20, 150], [330, 180], [300, 330], [60, 330]], st.body);        // tank
  line([P(520, -40), P(780, -10), P(1010, -110)], 60, st.body);          // front fender
  // rider, crouched on the pegs
  line([P(-40, -110), P(140, 330), P(-170, 360)], 120, st.suit);        // shin, thigh
  line([P(-170, 360), P(90, 820)], 150, st.suit);                       // torso
  line([P(90, 800), P(250, 620), P(300, 470)], 90, st.suit);            // arm
  cx.fillStyle = st.helmet; cx.beginPath(); cx.arc(...P(250, 1000), 140, 0, 7); cx.fill();
  if (st.cg) { cx.fillStyle = st.cg; cx.beginPath(); cx.arc(x, y, 55, 0, 7); cx.fill(); }
}
function ghostAt(g, rt) {
  const s = g.samples; if (!s.length || rt < s[0][7]) return null;
  let lo = 0, hi = s.length - 1; if (rt >= s[hi][7]) return null;
  while (hi - lo > 1) { const m = (lo + hi) >> 1; if (s[m][7] <= rt) lo = m; else hi = m; }
  const a = s[lo], b = s[hi], u = (rt - a[7]) / (b[7] - a[7]);
  if (Math.abs(b[0] - a[0]) > 20000) return a;
  return a.map((v, j) => j < 6 ? v + (b[j] - v) * u : v);
}
function drawBackground(W, H, camX, camY) {
  const g = cx.createLinearGradient(0, 0, 0, H); g.addColorStop(0, '#5ea8ef'); g.addColorStop(1, '#cfe9ff');
  cx.fillStyle = g; cx.fillRect(0, 0, W, H);
  if (!track) return;
  [[0.05, '#9fb7c9', 0.55, 160], [0.12, '#86a58a', 0.68, 110]].forEach(([par, col, base, amp], li) => {
    const h = track.hills[li], seg = W / 6;
    const off = (camX * par / 50) % seg, start = Math.floor(camX * par / 50 / seg);
    cx.fillStyle = col; cx.beginPath(); cx.moveTo(0, H);
    for (let k = -1; k < 9; k++) {
      const v = h[((start + k) % 64 + 64) % 64], v2 = h[((start + k + 1) % 64 + 64) % 64];
      const xa = k * seg - off;
      for (let q = 0; q <= 8; q++) { const u = q / 8, s = (1 - Math.cos(u * Math.PI)) / 2; cx.lineTo(xa + u * seg, H * base - amp * (v * (1 - s) + v2 * s)); }
    }
    cx.lineTo(W, H); cx.fill();
  });
}
function render(ms) {
  const W = cv.width = cv.clientWidth, H = cv.height = cv.clientHeight;
  if (!race) { drawBackground(W, H, performance.now() * 2, 0); return; }
  const st = race.prev;
  const speed = Math.hypot(st[S.VX], st[S.VY]) / 1e4; // m/s
  const targetZoom = 1 / (1 + Math.max(0, speed - 6) / 25);
  view.zoom += (targetZoom - view.zoom) * Math.min(1, ms / 400);
  const scale = H / 10000 * view.zoom;
  if (race.camY === null || Math.abs(race.camY - st[S.Y]) > 20000) race.camY = st[S.Y];
  race.camY += (st[S.Y] - race.camY) * Math.min(1, ms / 150);
  const camX = st[S.X] + 2500 * Math.min(1, speed / 20);
  drawBackground(W, H, camX, race.camY);
  cx.setTransform(scale, 0, 0, -scale, W * 0.42 - camX * scale, H * 0.58 + race.camY * scale);
  const dirt = cx.createLinearGradient(0, race.camY + 4000, 0, race.camY - 8000);
  dirt.addColorStop(0, '#8a5f33'); dirt.addColorStop(1, '#4e3519');
  cx.fillStyle = dirt; cx.fill(track.path);
  cx.strokeStyle = '#5b8f2e'; cx.lineWidth = 90; cx.lineJoin = 'round'; cx.stroke(track.edge);
  // lap line (crossing pts[n-40] wraps the bike back by one lap length, so draw it at both places)
  const lineX = track.pts[track.pts.length - 40][0];
  for (const lx of [lineX, lineX - track.lapLength]) {
    const gy = M._web_ground_y(lx);
    cx.fillStyle = '#eee'; cx.fillRect(lx - 40, gy, 80, 2600);
    for (let j = 0; j < 8; j++) for (let k = 0; k < 2; k++) {
      cx.fillStyle = (j + k) % 2 ? '#111' : '#fff'; cx.fillRect(lx + 40 + j * 120, gy + 2200 + k * 120, 120, 120);
    }
  }
  const fr = bikeParams[0], rr = bikeParams[8];
  for (const g of race.ghosts) {
    const s = ghostAt(g, st[S.RACE_TIME]); if (!s || st[S.STATE] !== 2) continue;
    drawBike(s[0], s[1], s[0] + s[2], s[1] + s[3], s[0] + s[4], s[1] + s[5], g.radii[0], g.radii[1], ghostStyle(g.color), null, null);
  }
  drawBike(st[S.X], st[S.Y], st[S.FWX], st[S.FWY], st[S.RWX], st[S.RWY], fr, rr, PLAYER_STYLE, st[S.WHEEL_F], st[S.WHEEL_R]);
  cx.setTransform(1, 0, 0, 1, 0, 0);
  // brake line hint
  cx.setLineDash([8, 8]); cx.strokeStyle = 'rgba(255,255,255,0.25)'; cx.lineWidth = 1;
  cx.beginPath(); cx.moveTo(0, H * BRAKE_FRAC); cx.lineTo(W, H * BRAKE_FRAC); cx.stroke(); cx.setLineDash([]);
  cx.fillStyle = 'rgba(255,255,255,0.4)'; cx.font = '12px monospace'; cx.fillText('brake below', 8, H * BRAKE_FRAC + 14);
  if (paused) { cx.fillStyle = 'rgba(0,0,0,.4)'; cx.fillRect(0, 0, W, H); }
  drawHud(st);
  const now = performance.now();
  $('msg').innerHTML = paused ? 'Paused' : (now < race.msgUntil ? race.msg : '');
  updateStatus();
}
const thrC = $('thr').getContext('2d'), rpmC = $('rpm').getContext('2d');
function drawHud(st) {
  const W = 150, H = 130, sy = H / 480, y = Math.min(480, 294 - st[S.THROTTLE] / 200) * sy;
  thrC.clearRect(0, 0, W, H);
  thrC.fillStyle = '#2e7d32'; thrC.fillRect(40, 0, 70, 294 * sy);
  thrC.fillStyle = '#8e1b1b'; thrC.fillRect(40, 294 * sy, 70, H - 294 * sy);
  thrC.fillStyle = '#ccc'; thrC.font = '10px monospace'; thrC.fillText('full', 4, 10); thrC.fillText('brake', 2, H - 4);
  const brake = st[S.THROTTLE] < 1 && st[S.GEAR] > 0;
  thrC.fillStyle = brake ? '#ff5252' : '#fff';
  thrC.fillRect(34, (brake ? 294 * sy + 6 : y) - 2, 82, 4);
  $('gear').textContent = st[S.ENGINE] ? (st[S.GEAR] ? st[S.GEAR] : 'N') : 'off';
  rpmC.fillStyle = '#333'; rpmC.fillRect(0, 0, 150, 12);
  rpmC.fillStyle = st[S.RPM] > 40000 ? '#ff7043' : '#ffca28'; rpmC.fillRect(0, 0, Math.max(0, Math.min(1, st[S.RPM] / TMAX)) * 150, 12);
  $('speed').textContent = `${(st[S.VX] / 1e4 * 3.6).toFixed(0)} km/h`;
}
function updateStatus() {
  if (!race) return;
  const st = race.prev, t = st[S.STATE] === 2 ? st[S.RACE_TIME] / 1000 : 0;
  $('status').textContent = `${track.name}  [${race.s.physics} physics]\n` +
    `Lap ${Math.min(track.laps, st[S.LAPS] + 1)} / ${track.laps}   Time ${t.toFixed(2)} s\n` +
    `Best ${race.best === null ? '–' : (race.best / 1000).toFixed(3) + ' s'}   Crashes ${st[S.CRASHES]}` +
    (track.allowGetBack ? '' : '\n(no getting back on after a crash!)');
}

// ---------------------------------------------------------------- menu & bike editor
function updateMenu() {
  const s = settings();
  $('seed').classList.toggle('hidden', s.track !== 'random');
  let desc = '';
  const src = window.DB_TRACKS.find(x => x.name === s.track);
  if (src) desc = src.description + `  (${src.laps} lap${src.laps > 1 ? 's' : ''}` +
    (src.ghosts.length ? `; records: ${src.ghosts.map(g => (g.samples[g.samples.length - 1][7] / 1000).toFixed(1) + 's').join(', ')})` : ')');
  else if (s.track === 'beginner') desc = "The original's built-in Beginner's Track.";
  else if (s.track === 'expert') desc = "The original's built-in Expert's Track.";
  else desc = 'A track from the original random track generator.';
  $('desc').textContent = desc;
  const b = store.get(bestKey(s), null);
  $('best').textContent = b ? `${(b.time / 1000).toFixed(3)} s` : '–';
  for (const k of ['track', 'seed', 'bike', 'physics', 'trans', 'ghosts', 'sound']) {
    const el = $(k); store.set('ui.' + k, el.type === 'checkbox' ? el.checked : el.value);
  }
}
function initMenu() {
  const sel = $('track');
  for (const t of window.DB_TRACKS) sel.add(new Option(t.name, t.name));
  sel.add(new Option("Beginner's Track (generated)", 'beginner'));
  sel.add(new Option("Expert's Track (generated)", 'expert'));
  sel.add(new Option('Random track…', 'random'));
  for (const k of ['track', 'seed', 'bike', 'physics', 'trans', 'ghosts', 'sound']) {
    const el = $(k), v = store.get('ui.' + k, null);
    if (v !== null) el.type === 'checkbox' ? (el.checked = v) : (el.value = v);
    el.addEventListener('change', updateMenu);
  }
  if (!$('seed').value) $('seed').value = Math.floor(Math.random() * 1e9);
  $('start').onclick = begin;
  $('editbike').onclick = openEditor;
  updateMenu();
}
